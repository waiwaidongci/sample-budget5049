from src.services import methods,migrations
def list_methods(db): return methods.list_versions(db)
def switch_method(db,data,user): return methods.switch(db,data.code,user)
def list_migrations(db): return migrations.list_batches(db)
def create_migration(db,data,user): return migrations.create_batch(db,user,data.target_method)
def get_migration(db,batch_id): return migrations.get_batch(db,batch_id)
def switch_migration(db,batch_id,user): return migrations.switch(db,batch_id,user)
def rollback_migration(db,batch_id,user): return migrations.rollback(db,batch_id,user)
def abandon_migration(db,batch_id,user): return migrations.abandon(db,batch_id,user)
